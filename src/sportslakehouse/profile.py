"""Write docs/data_profile.md from the Bronze layer (week 1 deliverable).

The report answers: how many matches per season, is the data complete, how big is the home
advantage, do dates parse, and which shots / odds columns exist in which season.
"""

from __future__ import annotations

from pathlib import Path

import duckdb
import pandas as pd

from sportslakehouse.config import Settings
from sportslakehouse.ingestion.inventory import first_season_with, inventory_from_frames, load_bronze_frames
from sportslakehouse.seasons import current_season_start, season_label

EXPECTED_MATCHES = 306  # 18 teams x 17 home matches
INTERESTING_COLUMNS = [
    "HS", "AS", "HST", "AST",  # shots, shots on target
    "B365H", "B365D", "B365A",  # Bet365 opening odds
    "B365CH", "B365CD", "B365CA",  # Bet365 closing odds
    "PSH", "PSD", "PSA", "PSCH", "PSCD", "PSCA",  # Pinnacle opening / closing
    "AvgH", "AvgD", "AvgA", "AvgCH", "AvgCD", "AvgCA",  # market average
]  # fmt: skip


def to_markdown(df: pd.DataFrame) -> str:
    """Tiny markdown table writer (avoids the `tabulate` dependency)."""
    if df.empty:
        return "_no data_\n"
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in row.tolist()) + " |")
    return "\n".join(lines) + "\n"


def per_season_summary(settings: Settings) -> pd.DataFrame:
    glob = str(settings.bronze_dir / "season=*" / f"{settings.league}.parquet")
    query = f"""
    WITH m AS (
      SELECT
        _season AS season,
        coalesce(try_strptime(Date, '%d/%m/%Y'), try_strptime(Date, '%d/%m/%y')) AS d,
        try_cast(FTHG AS INTEGER) AS hg,
        try_cast(FTAG AS INTEGER) AS ag,
        FTR
      FROM read_parquet('{glob}', union_by_name = true)
    )
    SELECT
      season,
      count(*)                                              AS n_matches,
      sum((d IS NULL)::INT)                                 AS bad_dates,
      min(d)::VARCHAR                                       AS first_date,
      max(d)::VARCHAR                                       AS last_date,
      round(avg((FTR = 'H')::INT), 3)                       AS home_win_rate,
      round(avg((FTR = 'D')::INT), 3)                       AS draw_rate,
      round(avg((FTR = 'A')::INT), 3)                       AS away_win_rate,
      round(avg(hg), 3)                                     AS home_goals_avg,
      round(avg(ag), 3)                                     AS away_goals_avg,
      sum((CASE WHEN hg > ag THEN 'H' WHEN hg = ag THEN 'D' ELSE 'A' END <> FTR)::INT)
                                                            AS result_mismatch
    FROM m
    GROUP BY season
    ORDER BY season
    """
    return duckdb.sql(query).df()


def build_report(settings: Settings) -> str:
    summary = per_season_summary(settings)
    current = season_label(current_season_start())
    summary["complete?"] = [
        "in progress" if s == current else ("OK" if n == EXPECTED_MATCHES else f"CHECK ({n})")
        for s, n in zip(summary["season"], summary["n_matches"], strict=True)
    ]
    inv = inventory_from_frames(load_bronze_frames(settings))

    avail = []
    for col in INTERESTING_COLUMNS:
        first = first_season_with(inv, col)
        avail.append({"column": col, "first season with data (>=50% filled)": first or "never"})

    parts = [
        "# Data profile: football-data.co.uk, Bundesliga (D1)\n",
        "Generated by `python -m sportslakehouse.profile`. Do not edit by hand.\n",
        f"- seasons in Bronze: **{summary['season'].nunique()}**",
        f"- matches in Bronze: **{int(summary['n_matches'].sum())}**",
        f"- seasons with a result/goals mismatch: **{int((summary['result_mismatch'] > 0).sum())}**",
        f"- seasons with unparseable dates: **{int((summary['bad_dates'] > 0).sum())}**\n",
        "## Matches and basic rates per season\n",
        to_markdown(summary),
        "## Where shots and odds columns start to exist\n",
        to_markdown(pd.DataFrame(avail)),
        "## Notes for the design document\n",
        "- Completed seasons should have exactly 306 matches (18 teams).",
        "- Odds and shots columns are not available for every season: pick the reference odds "
        "column per season and document the fallback in the README.",
        "- Home-win rate over time shows the home advantage (and the COVID seasons 2019/20 and "
        "2020/21 without spectators).",
    ]
    return "\n".join(parts) + "\n"


def main() -> None:
    settings = Settings()
    report = build_report(settings)
    out = Path("docs/data_profile.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
